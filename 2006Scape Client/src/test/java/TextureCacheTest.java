    @Test public void gammaRaisesEachChannelFractionToThePowerIndependently() throws Exception {
        for (int rgb : new int[] {0, 1, 0x123456, 0xffffff, 0x80ff01}) assertEquals(rgb, gamma(rgb, 1.0));
        assertEquals(0x401000, gamma(0x804000, 2.0));
        assertEquals(0x800000, gamma(0x400000, 0.5));
        assertEquals(0x008000, gamma(0x004000, 0.5));
        assertEquals(0x000040, gamma(0x000010, 0.5));
        assertEquals(0xfefefe, gamma(0xffffff, 2.0));
        assertEquals(0xfefefe, gamma(0xffffff, 1.4));
        assertTrue((gamma(0x808080, 0.6) & 0xff) > 0x80);
        assertTrue((gamma(0x808080, 1.5) & 0xff) < 0x80);
    }

